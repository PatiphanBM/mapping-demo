    [Fact]
    [Trait("Category", "PostgreSqlIntegration")]
    public async Task PostgreSql_catalog_discovers_table_and_classifies_drift()
    {
        var connectionString = Environment.GetEnvironmentVariable(
            "MAPPING_POSTGRES_TARGET_INTEGRATION") ??
            Environment.GetEnvironmentVariable("MAPPING_POSTGRES_INTEGRATION");
        if (string.IsNullOrWhiteSpace(connectionString))
        {
            Assert.NotEqual(
                "true",
                Environment.GetEnvironmentVariable(
                    "MAPPING_REQUIRE_POSTGRES_TARGET_INTEGRATION"));
            return;
        }

        var schemaName = $"phase29_{Guid.NewGuid():N}"[..30];
        var schema = SqlIdentifier.Quote(schemaName);
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync();
        try
        {
            await connection.ExecuteAsync($"""
                CREATE SCHEMA {schema};
                CREATE TABLE {schema}.customer (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    code varchar(20) NOT NULL UNIQUE,
                    note text NULL,
                    created_at timestamptz NOT NULL DEFAULT now(),
                    code_length integer GENERATED ALWAYS AS
                        (char_length(code)) STORED
                );
                """);
            var inspector = Inspector(
                "postgres-target",
                DatabaseProvider.PostgreSql,
                schemaName,
                connectionString);

            var tables = await inspector.ListTablesAsync(
                "postgres-target",
                schemaName);
            Assert.Contains(tables, table => table.Table == "customer");
            var original = await inspector.InspectAsync(
                new TargetTableReference(
                    "postgres-target",
                    schemaName,
                    "customer"),
                refresh: true);

            Assert.Contains(original.Columns, column =>
                column.Name == "id" && column.IsIdentity && !column.IsWritable);
            Assert.Contains(original.Columns, column =>
                column.Name == "code_length" && column.IsGenerated &&
                !column.IsWritable);
            Assert.Contains(original.UniqueConstraints, key =>
                key.Columns.SequenceEqual(["code"]));

            await connection.ExecuteAsync(
                $"ALTER TABLE {schema}.customer ADD COLUMN extra text NULL;");
            var additive = await inspector.InspectAsync(
                new TargetTableReference(
                    "postgres-target",
                    schemaName,
                    "customer"),
                refresh: true);
            var compatible = TargetSchemaCompatibilityAnalyzer.Compare(
                original.ToSnapshot(),
                additive,
                new HashSet<string>(["code"], StringComparer.Ordinal),
                ["code"]);
            Assert.Equal(
                SchemaCompatibilityStatus.CompatibleChange,
                compatible.Status);

            await connection.ExecuteAsync(
                $"ALTER TABLE {schema}.customer ADD COLUMN required_value integer NOT NULL;");
            var breaking = await inspector.InspectAsync(
                new TargetTableReference(
                    "postgres-target",
                    schemaName,
                    "customer"),
                refresh: true);
            Assert.Equal(
                SchemaCompatibilityStatus.BreakingChange,
                TargetSchemaCompatibilityAnalyzer.Compare(
                    additive.ToSnapshot(),
                    breaking,
                    new HashSet<string>(["code"], StringComparer.Ordinal),
                    ["code"]).Status);
        }
        finally
        {
            await connection.ExecuteAsync(
                $"DROP SCHEMA IF EXISTS {schema} CASCADE;");
        }
    }

    [Fact]
    [Trait("Category", "SqlServerIntegration")]
    public async Task SqlServer_catalog_discovers_table_and_classifies_drift()
    {
        var connectionString = Environment.GetEnvironmentVariable(
            "MAPPING_SQLSERVER_TARGET_INTEGRATION");
        if (string.IsNullOrWhiteSpace(connectionString))
        {
            Assert.NotEqual(
                "true",
                Environment.GetEnvironmentVariable(
                    "MAPPING_REQUIRE_SQLSERVER_TARGET_INTEGRATION"));
            return;
        }

        var schemaName = $"phase29_{Guid.NewGuid():N}"[..30];
        var schema = QuoteSqlServer(schemaName);
        await using var connection = new SqlConnection(connectionString);
        await connection.OpenAsync();
        try
        {
            await connection.ExecuteAsync($"CREATE SCHEMA {schema};");
            await connection.ExecuteAsync($"""
                CREATE TABLE {schema}.[customer] (
                    [id] bigint IDENTITY(1,1) NOT NULL PRIMARY KEY,
                    [code] nvarchar(20) NOT NULL UNIQUE,
                    [note] nvarchar(50) NULL,
                    [code_length] AS LEN([code]),
                    [stamp] rowversion
                );
                """);
            var inspector = Inspector(
                "sqlserver-target",
                DatabaseProvider.SqlServer,
                schemaName,
                connectionString);

            Assert.Contains(
                await inspector.ListTablesAsync(
                    "sqlserver-target",
                    schemaName),
                table => table.Table == "customer");
            var original = await inspector.InspectAsync(
                new TargetTableReference(
                    "sqlserver-target",
                    schemaName,
                    "customer"),
                refresh: true);
            Assert.Contains(original.Columns, column =>
                column.Name == "id" && column.IsIdentity && !column.IsWritable);
            Assert.Contains(original.Columns, column =>
                column.Name == "stamp" && !column.IsWritable);
            Assert.Contains(original.UniqueConstraints, key =>
                key.Columns.SequenceEqual(["code"]));

            await connection.ExecuteAsync(
                $"ALTER TABLE {schema}.[customer] ADD [extra] int NULL;");
            var additive = await inspector.InspectAsync(
                new TargetTableReference(
                    "sqlserver-target",
                    schemaName,
                    "customer"),
                refresh: true);
            Assert.Equal(
                SchemaCompatibilityStatus.CompatibleChange,
                TargetSchemaCompatibilityAnalyzer.Compare(
                    original.ToSnapshot(),
                    additive,
                    new HashSet<string>(["code"], StringComparer.Ordinal),
                    ["code"]).Status);

            await connection.ExecuteAsync(
                $"ALTER TABLE {schema}.[customer] ADD [required_value] int NOT NULL;");
            var breaking = await inspector.InspectAsync(
                new TargetTableReference(
                    "sqlserver-target",
                    schemaName,
                    "customer"),
                refresh: true);
            Assert.Equal(
                SchemaCompatibilityStatus.BreakingChange,
                TargetSchemaCompatibilityAnalyzer.Compare(
                    additive.ToSnapshot(),
                    breaking,
                    new HashSet<string>(["code"], StringComparer.Ordinal),
                    ["code"]).Status);
        }
        finally
        {
            await connection.ExecuteAsync($"""
                IF OBJECT_ID(N'{schemaName}.customer', N'U') IS NOT NULL
                    DROP TABLE {schema}.[customer];
                IF SCHEMA_ID(N'{schemaName}') IS NOT NULL
                    EXEC(N'DROP SCHEMA {schema}');
                """);
        }
    }

    private static IDatabaseTargetSchemaInspector Inspector(
        string profileId,
        DatabaseProvider provider,
        string schema,
        string connectionString)
    {
        const string connectionName = "Target";
        var profile = new DatabaseDestinationProfile(
            profileId,
            provider,
            connectionName,
            [schema],
            30,
            60,
            WriteEnabled: false,
            "sha256:test-profile");
        var catalog = new DatabaseDestinationProfileCatalog([profile]);
        var configuration = new ConfigurationBuilder()
            .AddInMemoryCollection(new Dictionary<string, string?>
            {
                [$"ConnectionStrings:{connectionName}"] = connectionString
            })
            .Build();
        var factory = new DatabaseDestinationConnectionFactory(
            catalog,
            configuration);
        return new DatabaseTargetSchemaInspector(catalog, factory);
    }

    private static string QuoteSqlServer(string identifier) =>
        $"[{identifier.Replace("]", "]]", StringComparison.Ordinal)}]";
}
